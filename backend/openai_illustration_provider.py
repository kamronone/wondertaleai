"""Opt-in OpenAI Images API adapter for an operator-managed private worker.

No HTTP endpoint imports or invokes this module. No key, prompt, output or
provider response is logged. The separate queue worker enforces job quotas,
owner checks and independent prompt + image moderation before persistence.
"""
import base64
import binascii
import os
from typing import Any

from private_illustration_media import MAX_INPUT_BYTES, normalize_private_illustration

# Pinned pilot model avoids surprise upgrades to higher-priced image models.
PILOT_IMAGE_MODEL="gpt-image-1.5"
MAX_BASE64_LENGTH=((MAX_INPUT_BYTES+2)//3)*4


def generate_private_illustration(prompt:str,client:Any=None)->bytes:
    """Generate one metadata-stripped PNG; never retry a potentially paid call.

    Client injection is for tests. Calling the adapter alone does NOT provide
    child-safety or output-moderation approval. Production code must supply a
    separate reviewed moderation implementation around this adapter.
    """
    if os.getenv("ENABLE_AI_ILLUSTRATIONS","false").lower()!="true":
        raise RuntimeError("Private illustration generation is disabled")
    if os.getenv("ENABLE_AI_ILLUSTRATIONS_WORKER","false").lower()!="true":
        raise RuntimeError("Private illustration worker is disabled")
    if os.getenv("ENABLE_OPENAI_IMAGE_PROVIDER","false").lower()!="true":
        raise RuntimeError("OpenAI image provider is disabled")
    if os.getenv("APP_ENV","development").lower() not in ("development","preview","staging"):
        raise RuntimeError("OpenAI illustration pilot refuses production")
    if os.getenv("OPENAI_IMAGE_MODEL",PILOT_IMAGE_MODEL)!=PILOT_IMAGE_MODEL:
        raise RuntimeError("Unapproved illustration model")
    if not isinstance(prompt,str) or not 60<=len(prompt)<=2500:
        raise ValueError("Invalid illustration prompt")
    # Restrict the adapter to generic safe briefs generated by the internal
    # planner, rather than untrusted free-form child data.
    from illustration_planning import SAFETY, STYLES, MASCOTS
    if not prompt.endswith(SAFETY) or not any(prompt.startswith(x+".") for x in STYLES.values()) or not any(mascot in prompt for mascot in MASCOTS):
        raise ValueError("Only curated generic illustration prompts are allowed")
    if client is None:
        if not os.getenv("OPENAI_API_KEY"):
            raise RuntimeError("OPENAI_API_KEY is not configured")
        from openai import OpenAI
        client=OpenAI(timeout=90,max_retries=0)

    response=client.images.generate(
        model=PILOT_IMAGE_MODEL,
        prompt=prompt,
        size="1024x1024",
        n=1,
        output_format="png",
    )
    data=getattr(response,"data",None)
    if not isinstance(data,(list,tuple)) or len(data)!=1:
        raise ValueError("Invalid provider image count")
    encoded=getattr(data[0],"b64_json",None)
    if not isinstance(encoded,str) or not encoded or len(encoded)>MAX_BASE64_LENGTH:
        raise ValueError("Invalid provider image payload size")
    try:
        raw=base64.b64decode(encoded,validate=True)
    except (binascii.Error,ValueError) as exc:
        raise ValueError("Invalid base64 image payload") from exc
    if len(raw)>MAX_INPUT_BYTES:
        raise ValueError("Provider image exceeds allowed size")
    return normalize_private_illustration(raw)
